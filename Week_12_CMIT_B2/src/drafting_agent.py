def draft_case_brief() -> str:
    """Drafts a comprehensive Case Brief for a Supreme Court of Pakistan judgment."""
    brief = f"""# LEGAL CASE BRIEF: FEDERATION OF PAKISTAN v. MESSRS SUNRISE ENTERPRISES

{WATERMARK}

## 1. Case Citation & Metadata
- **Reported Citation:** **2021 SCMR 105** (also cited as 2021 SC 850)
- **Court:** Supreme Court of Pakistan (Appellate Jurisdiction)
- **Bench:** 5-Judge Full Bench
  - Hon'ble Mr. Justice Gulzar Ahmed, Chief Justice of Pakistan
  - Hon'ble Mr. Justice Umar Ata Bandial
  - Hon'ble Mr. Justice Qazi Faez Isa
  - Hon'ble Mr. Justice Syed Mansoor Ali Shah *(Authoring Judge)*
  - Hon'ble Mr. Justice Munib Akhtar
- **Date of Decision:** 14th January 2021
- **Area of Law:** Contract Law, Statutory Validity, Public Policy, Government Procurement

---

## 2. Statutory Provisions Interpreted
- **Section 23, Contract Act, 1872:** *(What considerations and objects are lawful and what not)*
- **Section 24, Contract Act, 1872:** *(Agreements void, if considerations and objects unlawful in part)*
- **Section 65, Contract Act, 1872:** *(Obligation of person who has received advantage under void agreement)*
- **Article 189, Constitution of the Islamic Republic of Pakistan, 1973:** *(Decisions of Supreme Court binding on other courts)*

---

## 3. Factual Background
The Federation of Pakistan entered into a commercial public-private procurement agreement with Messrs Sunrise Enterprises for supply of strategic logistics equipment. A dispute arose when audit authorities discovered that a component of the contractual consideration involved unauthorized customs duty exemptions and kickbacks in direct violation of the Customs Act, 1969. The respondent contractor filed a suit claiming partial severance of the agreement under the doctrine established in *Government of NWFP v. Malik Said Muhammad (1998 SCMR 1120)*, arguing that the lawful supply portions could still be enforced.

---

## 4. Key Legal Issues
1. **Severability of Unlawful Consideration:** Can an agreement tainted by unlawful consideration or object under Section 23 of the Contract Act, 1872 be severed to allow enforcement of the lawful components?
2. **Correctness of 1998 SCMR 1120:** Did the earlier 2-judge bench in *1998 SCMR 1120* correctly interpret the mandatory prohibition of Section 23 and Section 24?
3. **Public Policy Bar:** Can a party seek damages or restitution under Section 65 when the underlying transaction defeated an express statutory enactment?

---

## 5. Decision & Holding
1. **Express Overruling of 1998 SCMR 1120:** The 5-Judge Full Bench unanimously held that *Government of NWFP v. Malik Said Muhammad (1998 SCMR 1120)* was decided contrary to the clear statutory command of Section 23 and Section 24. **1998 SCMR 1120 is expressly OVERRULED as bad law.**
2. **Indivisibility of Illegality:** Under Section 23, if any single part of the consideration or object of an agreement is forbidden by law or opposed to public policy, the entire agreement is void *ab initio*. Severance cannot be deployed to rescue an agreement tainted with statutory illegality.
3. **Refusal of Judicial Enforcement:** Courts in Pakistan will not extend assistance to enforce or grant restitution for contracts entered into in contravention of statutory mandates (*ex turpi causa non oritur actio*).

---

## 6. Precedential Significance for Khan & Associates
- **Overruling Alert:** In litigation and contract vetting, counsel must ensure that no reliance is placed on *1998 SCMR 1120*.
- **Drafting Recommendation:** Commercial contracts involving government bodies or regulatory licensing must contain robust representations confirming statutory compliance, as any illegal consideration invalidates the entire instrument without the possibility of severance.
"""
    return brief


